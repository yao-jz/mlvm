package cmd

import (
	"debug/elf"
	"fmt"

	"github.com/ethereum-optimism/optimism/op-service/jsonutil"
	"github.com/urfave/cli/v2"

	"github.com/yao-jz/mlvm/rvgo/fast"
)

var ELFPathFlag = &cli.PathFlag{
	Name:     "path",
	Usage:    "Path to a statically linked RV64IMAFD ELF",
	Required: true,
}

var StateOutputFlag = &cli.PathFlag{
	Name:  "out",
	Usage: "Output path for the initial JSON state; use - for stdout",
	Value: "state.json",
}

var MetadataOutputFlag = &cli.PathFlag{
	Name:  "meta",
	Usage: "Output path for optional ELF symbol metadata",
	Value: "meta.json",
}

var LoadFileFlag = &cli.StringSliceFlag{
	Name: "load-file",
	Usage: "Stage a file into guest memory. Use path for a verbatim guest name, or " +
		"guestPath=hostPath to bind a stable committed name to a host file",
	Required: false,
}

var QuietFlag = &cli.BoolFlag{
	Name:     "quiet",
	Usage:    "Suppress the per-segment ELF mapping report",
	Required: false,
}

// RandomFileFlag points at the blob of pre-generated bytes that getrandom(2) serves from.
// It is part of the committed initial state rather than a host resource, because two
// parties replaying the same trace must observe the same bytes.
var RandomFileFlag = &cli.PathFlag{
	Name:     "random-file",
	Usage:    "Optional deterministic byte blob (up to 5 MiB) for getrandom(2); defaults to zero-filled memory",
	Required: false,
}

func LoadELF(ctx *cli.Context) error {
	// load-elf is a one-shot command whose whole job is to report what it mapped where,
	// so the segment/patch trace is on unless explicitly silenced. `run` is the opposite:
	// it executes millions of steps, so its trace is off unless --trace is passed.
	fast.Trace = !ctx.Bool(QuietFlag.Name)

	elfPath := ctx.Path(ELFPathFlag.Name)
	loadFiles := ctx.StringSlice(LoadFileFlag.Name)
	if len(loadFiles) > 0 && !ctx.Bool(QuietFlag.Name) {
		fmt.Printf("staging files: %q\n", loadFiles)
	}
	elfProgram, err := elf.Open(elfPath)
	if err != nil {
		return fmt.Errorf("failed to open ELF file %q: %w", elfPath, err)
	}
	if elfProgram.Machine != elf.EM_RISCV {
		return fmt.Errorf("ELF is not RISC-V, but got %q", elfProgram.Machine.String())
	}
	state, err := fast.LoadELF(elfProgram)
	if err != nil {
		return fmt.Errorf("failed to load ELF data into VM state: %w", err)
	}
	err = fast.PatchVM(elfProgram, state)
	if err != nil {
		return fmt.Errorf("failed to patch VM: %w", err)
	}
	// Map the committed randomness blob, then stage any requested input files.
	if err := state.LoadRandomNumberFile(ctx.Path(RandomFileFlag.Name)); err != nil {
		return err
	}
	err = fast.LoadFile(loadFiles, state)
	if err != nil {
		return fmt.Errorf("failed to load file: %w", err)
	}
	meta, err := MakeMetadata(elfProgram)
	if err != nil {
		return fmt.Errorf("failed to compute program metadata: %w", err)
	}
	if err := jsonutil.WriteJSON[*Metadata](ctx.Path(MetadataOutputFlag.Name), meta, OutFilePerm); err != nil {
		return fmt.Errorf("failed to output metadata: %w", err)
	}
	return jsonutil.WriteJSON[*fast.VMState](ctx.Path(StateOutputFlag.Name), state, OutFilePerm)
}

var LoadELFCommand = &cli.Command{
	Name:        "load-elf",
	Usage:       "Load a RISC-V ELF into an MLVM JSON state",
	Description: "Load a RISC-V ELF into committed memory and optionally stage deterministic input files.",
	Action:      LoadELF,
	Flags: []cli.Flag{
		ELFPathFlag,
		StateOutputFlag,
		MetadataOutputFlag,
		LoadFileFlag,
		QuietFlag,
		RandomFileFlag,
	},
}
