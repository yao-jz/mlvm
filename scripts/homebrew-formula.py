#!/usr/bin/env python3
"""Write the Homebrew formula for a tagged release from its checksums.txt.

    python3 scripts/homebrew-formula.py --version 0.1.0 --checksums dist/checksums.txt > mlvm.rb

The release workflow commits the result to github.com/yao-jz/homebrew-tap as
Formula/mlvm.rb, so `brew install yao-jz/tap/mlvm` installs the prebuilt binary.
"""
import argparse
import pathlib
import sys

REPO = "yao-jz/mlvm"
TARGETS = [("darwin", "arm64"), ("darwin", "amd64"), ("linux", "arm64"), ("linux", "amd64")]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", required=True, help="without the leading v")
    ap.add_argument("--checksums", required=True)
    args = ap.parse_args()

    sums = {}
    for line in pathlib.Path(args.checksums).read_text().splitlines():
        digest, name = line.split()
        sums[name.lstrip("*")] = digest

    def block(goos, goarch, indent):
        name = f"mlvm_{args.version}_{goos}_{goarch}.tar.gz"
        if name not in sums:
            raise SystemExit(f"error: {name} is not in {args.checksums}")
        pad = " " * indent
        return (f'{pad}url "https://github.com/{REPO}/releases/download/v{args.version}/{name}"\n'
                f'{pad}sha256 "{sums[name]}"\n')

    out = f'''# Generated by scripts/homebrew-formula.py from the v{args.version} release checksums.
class Mlvm < Formula
  desc "Deterministic RISC-V virtual machine for machine learning"
  homepage "https://github.com/{REPO}"
  version "{args.version}"
  license "MIT"

  on_macos do
    on_arm do
{block("darwin", "arm64", 6)}    end
    on_intel do
{block("darwin", "amd64", 6)}    end
  end

  on_linux do
    on_arm do
{block("linux", "arm64", 6)}    end
    on_intel do
{block("linux", "amd64", 6)}    end
  end

  def install
    bin.install "mlvm"
  end

  test do
    assert_match "{args.version}", shell_output("#{{bin}}/mlvm --version")
    assert_match "passed=true", shell_output("#{{bin}}/mlvm demo --max-new-tokens 4")
  end
end
'''
    sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
