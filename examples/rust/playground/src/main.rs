
fn main() {
    // test floating point operation
    let x: f32 = 2.1234;
    let y: f32 = 3.4567;

    // addition
    let sum = x + y;
    println!("sum: {}", sum);
    
    // subtraction
    let difference = x - y;
    println!("difference: {}", difference);

    // multiplication
    let product = x * y;
    println!("product: {}", product);

    // division
    let quotient = x / y;
    println!("quotient: {}", quotient);

    // remainder
    let remainder = x % y;
    println!("remainder: {}", remainder);
    
}